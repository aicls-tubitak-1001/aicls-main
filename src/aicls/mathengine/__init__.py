"""Typed CAS commands executed by SymPy in a sandboxed worker pool, with cache and plots.

This package is the deterministic core of İP-4: everything the user is told is a *result* comes
from here, computed by SymPy, never generated by a model. Public entry points
(docs/mimari/moduller.md, ADR-0016)::

    CasCommand = Diff | Integrate | Limit | Solve | Simplify | Expand | Factor
               | Series | Evaluate | Plot            # discriminated on `op`
    MathEngine(executor, cache, timeout_s).execute(cmd) -> Result
    InProcessExecutor()                               # tests and CLI (thread timeout only)
    PoolExecutor(...)                                 # production: warm spawn pool, kill+respawn
    symbolic_equivalent(a, b) -> "equal" | "different" | "unparsable"
    render_plot(expr, var, xmin, xmax) -> bytes       # deterministic Matplotlib Agg PNG

Only :class:`aicls.core.errors.AiclsError` subclasses leave the package:
:class:`UnsupportedProblem` (the frozen İP-4 sentence
:data:`aicls.core.messages_tr.MSG_UNSUPPORTED_PROBLEM`), :class:`CasTimeout`,
``InputValidationError`` for the :data:`MAX_INPUT_CHARS` limit, and the parser's ``ParseError``
/ ``UnsupportedConstruct`` passed through from :mod:`aicls.latex2sympy`.
"""

