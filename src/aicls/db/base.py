"""Declarative base, naming convention and reusable column types.

All models inherit from :class:`Base`, whose :class:`~sqlalchemy.MetaData` carries the constraint
naming convention required by Alembic's ``render_as_batch`` recreation of SQLite tables
(docs/mimari/veri-modeli.md §1). The column aliases below encode the dialect-neutrality rules:
ULID string primary keys, an explicit length on every string, ``sa.JSON`` documents, naive UTC
timestamps and no server-side defaults.
"""

from __future__ import annotations

from datetime import UTC, date, datetime
from typing import Annotated, Any

from sqlalchemy import (
    CHAR,
    JSON,
    Boolean,
    Date,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Integer,
    MetaData,
    String,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, MappedColumn, mapped_column

from aicls.core.ids import ulid
from aicls.db.enums import ENUM_LENGTH

#: Constraint naming convention (docs/mimari/veri-modeli.md §1). Every constraint must be named
#: for ``op.batch_alter_table`` to be able to recreate a SQLite table.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

#: MySQL storage options appended to every ``__table_args__`` (ADR-0003: InnoDB + utf8mb4).
#: Ignored by SQLite, which has no table options.
MYSQL_TABLE_KWARGS: dict[str, str] = {
    "mysql_engine": "InnoDB",
    "mysql_charset": "utf8mb4",
    "mysql_collate": "utf8mb4_0900_ai_ci",
}

#: Length of a ULID string primary key.
ULID_LENGTH = 26
#: Width of a digest column: fits both a bare SHA-256 hex digest (64) and the prefixed
#: ``"sha256:<hex>"`` form returned by :mod:`aicls.core.hashing` (71).
DIGEST_LENGTH = 80
#: Width of a git commit SHA-1.
GIT_SHA_LENGTH = 40


def utcnow() -> datetime:
    """Return the current UTC time as a naive :class:`~datetime.datetime`.

    Timestamps are stored without a timezone offset (docs/mimari/veri-modeli.md §1 rule 5) so the
    same value round-trips through SQLite and MySQL; every writer uses UTC.
    """
    return datetime.now(UTC).replace(tzinfo=None)


def enum_column(enum_cls: type[Any], name: str) -> Enum:
    """Return a dialect-neutral ``VARCHAR`` enum column type.

    Args:
        enum_cls: The :class:`~enum.StrEnum` subclass to persist.
        name: Constraint name fragment; the CHECK constraint becomes ``ck_<table>_<name>``.

    Returns:
        A :class:`sqlalchemy.Enum` storing member *values* with ``native_enum=False``.
    """
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        length=ENUM_LENGTH,
        create_constraint=True,
        validate_strings=True,
        values_callable=lambda cls: [member.value for member in cls],
    )


# ---------------------------------------------------------------------------------------------
# Reusable annotated column types (SQLAlchemy 2.0 annotated declarative)
# ---------------------------------------------------------------------------------------------
#: ULID primary key, ``CHAR(26)``, generated by :func:`aicls.core.ids.ulid`.
UlidPk = Annotated[str, mapped_column(CHAR(ULID_LENGTH), primary_key=True, default=ulid)]
#: A ULID reference or opaque ULID-shaped value that is not a foreign key.
UlidStr = Annotated[str, mapped_column(CHAR(ULID_LENGTH))]
#: SHA-256 digest, bare hex or ``sha256:``-prefixed.
Digest = Annotated[str, mapped_column(String(DIGEST_LENGTH))]
#: Git commit SHA-1 (40 hex characters).
GitSha = Annotated[str, mapped_column(CHAR(GIT_SHA_LENGTH))]
#: JSON document column (``TEXT`` on SQLite, native ``JSON`` on MySQL).
JsonDoc = Annotated[dict[str, Any], mapped_column(JSON)]
#: Naive UTC timestamp.
Utc = Annotated[datetime, mapped_column(DateTime)]


def ulid_fk(
    target: str,
    *,
    ondelete: str = "CASCADE",
    nullable: bool = False,
    index: bool = False,
    unique: bool = False,
) -> MappedColumn[Any]:
    """Return a ``CHAR(26)`` foreign-key column pointing at ``target``.

    Primary and foreign key columns must share the exact same type for MySQL to accept the
    constraint, so both sides use ``CHAR(26)``.

    Args:
        target: ``"<table>.<column>"`` the key references.
        ondelete: Referential action; ``"CASCADE"`` for owned rows, ``"SET NULL"`` for optional
            back-references, ``"RESTRICT"`` for rows that must not disappear silently.
        nullable: Whether the reference is optional.
        index: Create a single-column index for the join.
        unique: Enforce a one-to-one relationship.
    """
    return mapped_column(
        CHAR(ULID_LENGTH),
        ForeignKey(target, ondelete=ondelete),
        nullable=nullable,
        index=index,
        unique=unique,
    )


class Base(DeclarativeBase):
    """Declarative base for every AI-CLS table.

    Carries the shared :class:`~sqlalchemy.MetaData` (naming convention) and the
    ``type_annotation_map`` that turns ``Mapped[dict[str, Any]]`` into ``sa.JSON`` and
    ``Mapped[datetime]`` into a naive ``DateTime``.
    """

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map = {
        dict[str, Any]: JSON,
        list[Any]: JSON,
        datetime: DateTime,
        date: Date,
        bool: Boolean,
        float: Float,
        int: Integer,
    }

    def __repr__(self) -> str:
        """``<Table id=...>`` — safe for logs (never renders user content)."""
        identifier = getattr(self, "id", None)
        return f"<{type(self).__name__} id={identifier!r}>"


class TimestampMixin:
    """``created_at`` / ``updated_at`` columns kept in naive UTC by the application.

    No server-side default or ``ON UPDATE`` clause is used (dialect rule 5): the values come from
    :func:`utcnow` so SQLite and MySQL behave identically and Alembic autogenerate stays clean.
    """

    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=utcnow, onupdate=utcnow, nullable=False
    )


