"""Training infrastructure: configs, registry, run manifests, trainer, tracking, checkpoints.

This package assembles the public surface promised by ``docs/mimari/moduller.md`` (section
``aicls.ml``) and ``docs/ml/egitim-altyapisi.md``. Importing it is deliberately **torch-free**:
every submodule keeps ``torch``, ``transformers``, ``peft`` and ``accelerate`` behind lazy imports
inside the functions that need them, so ``import aicls.ml`` costs no CUDA probe and no 2 s wheel
load. ``tests/integration/test_ml_contracts.py`` pins that guarantee in a subprocess.

Three names are exported from more than one submodule and are therefore **not** re-exported flat,
because a flat alias would silently pick one of two different objects:

* ``FitReport`` — :class:`aicls.ml.trainer.FitReport` (the OCR loop's pydantic report) is exported
  under its own name; the Whisper wrapper's dataclass is exported as :class:`WhisperFitReport`.
* ``METRICS_FILENAME`` — ``metrics.jsonl`` in :mod:`aicls.ml.tracking` but ``metrics.json`` in
  :mod:`aicls.ml.checkpoint`. Import it from the submodule that owns the file you mean.
* ``require_transformers`` — :mod:`aicls.ml.registry` and :mod:`aicls.ml.whisper_ft` raise
  different typed errors. Import it from the submodule you are calling into.

Every submodule stays importable as ``aicls.ml.<name>`` after importing this package.
"""

