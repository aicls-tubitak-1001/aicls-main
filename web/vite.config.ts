import { fileURLToPath, URL } from "node:url";

import react from "@vitejs/plugin-react";
import { defineConfig } from "vitest/config";

/**
 * Vite configuration for the AI-CLS SPA.
 *
 * The dev server proxies `/api` and `/ws` to the FastAPI process on 127.0.0.1:8000 so that the
 * browser sees a single origin (same-origin cookies for `aicls_refresh`, no CORS in development).
 * In production Caddy serves `web/dist` and proxies the same two prefixes (ADR-0018).
 */
export default defineConfig({
  plugins: [react()],
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
  server: {
    port: 5173,
    strictPort: true,
    proxy: {
      "/api": {
        target: "http://127.0.0.1:8000",
        changeOrigin: false,
      },
      "/ws": {
        target: "http://127.0.0.1:8000",
        ws: true,
        changeOrigin: false,
      },
    },
  },
  build: {
    outDir: "dist",
    sourcemap: true,
    target: "es2022",
    rollupOptions: {
      output: {
        // Split the two heavy, rarely-changing dependencies out of the application chunk: a
        // lecture starts with a cold cache once and then re-uses React and KaTeX across deploys.
        manualChunks: {
          react: ["react", "react-dom", "react-router-dom"],
          katex: ["katex"],
        },
      },
    },
  },
  test: {
    environment: "jsdom",
    globals: false,
    setupFiles: ["./src/test/setup.ts"],
    include: ["src/**/*.test.ts", "src/**/*.test.tsx"],
    exclude: ["e2e/**", "node_modules/**"],
    restoreMocks: true,
    coverage: {
      provider: "v8",
      reporter: ["text", "lcov"],
      reportsDirectory: "coverage",
      include: ["src/**/*.ts", "src/**/*.tsx"],
      exclude: [
        "src/main.tsx", // browser bootstrap: no logic, cannot run under jsdom
        "src/test/**",
        "src/api/generated/**", // generated by openapi-typescript
        // Type-only modules: they compile to nothing, so every line is "uncovered" by definition.
        "src/api/types.ts",
        "src/api/schema.ts",
        "src/**/*.d.ts",
        "src/**/*.test.ts",
        "src/**/*.test.tsx",
      ],
      thresholds: {
        lines: 70,
        statements: 70,
        functions: 70,
        branches: 70,
      },
    },
  },
});
